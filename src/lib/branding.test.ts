import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { readFileSync, readdirSync } from 'node:fs'
import { resolve } from 'node:path'

const mocks = vi.hoisted(() => ({
  decks: [] as Array<{ author: string; company: string }>,
  text: vi.fn((_value: unknown, ..._options: unknown[]) => undefined),
  writePptx: vi.fn(async (_options: { fileName: string }) => undefined),
  writeExcel: vi.fn(async (_data: unknown, _options: { fileName: string }) => undefined),
  documents: [] as Array<Record<string, unknown>>,
}))

vi.mock('pptxgenjs', () => ({
  default: class {
    author = ''
    company = ''
    layout = ''
    title = ''
    subject = ''
    ShapeType = { line: 'line', roundRect: 'roundRect', rect: 'rect' }
    ChartType = { bar: 'bar' }
    writeFile = mocks.writePptx
    constructor() { mocks.decks.push(this) }
    addSlide() {
      return { background: {}, addText: mocks.text, addShape: vi.fn(), addChart: vi.fn() }
    }
  },
}))

vi.mock('write-excel-file', () => ({ default: mocks.writeExcel }))
vi.mock('docx', () => ({
  Document: class { constructor(options: Record<string, unknown>) { mocks.documents.push(options) } },
  Packer: { toBlob: async () => new Blob(['ID-8 document']) },
  Paragraph: class { constructor(_options: unknown) {} },
  TextRun: class { constructor(_options: unknown) {} },
  HeadingLevel: { TITLE: 'title', HEADING_1: 'h1', HEADING_2: 'h2', HEADING_3: 'h3' },
}))

import { exportSessionToPptx } from './pptx-export'
import { exportPortfolioWorkbook } from './excel-export'
import { artifactFilename, downloadDocxFromMarkdown } from './engagement/exports'
import { buildTeamsSummary } from './share-helpers'

const root = resolve(import.meta.dirname, '..', '..')

describe('ID-8 branding across media', () => {
  beforeEach(() => {
    vi.clearAllMocks()
    mocks.decks.length = 0
    mocks.documents.length = 0
  })
  afterEach(() => {
    vi.unstubAllGlobals()
    vi.restoreAllMocks()
  })

  it('uses ID-8 in PowerPoint authorship, attribution and downloaded filenames', async () => {
    await exportSessionToPptx({ customerName: 'Contoso' })
    expect(mocks.decks[0].author).toBe('ID-8')
    expect(mocks.writePptx.mock.calls[0][0].fileName).toMatch(/^ID-8-Contoso-\d{4}-\d{2}-\d{2}\.pptx$/)
    expect(mocks.text.mock.calls.some(([text]) => typeof text === 'string' && text.includes('Generated by ID-8'))).toBe(true)
  })

  it('preserves a supplied author rather than replacing customer data', async () => {
    await exportSessionToPptx({ customerName: 'Contoso', preparedBy: 'Engagement Lead' })
    expect(mocks.decks[0].author).toBe('Engagement Lead')
  })

  it('uses ID-8 for workbook and engagement artifact filenames', async () => {
    await exportPortfolioWorkbook([])
    expect(mocks.writeExcel.mock.calls[0][1].fileName).toBe('ID-8-pipeline-plan.xlsx')
    expect(artifactFilename('Contoso', 'agenda', 'docx')).toMatch(/^ID-8-contoso-agenda-\d{4}-\d{2}-\d{2}\.docx$/)
  })

  it('sets ID-8 Word metadata and retains the requested document title', async () => {
    vi.stubGlobal('URL', { createObjectURL: () => 'blob:id8-test', revokeObjectURL: vi.fn() })
    vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => undefined)
    await downloadDocxFromMarkdown('# Agenda', 'ID-8-agenda.docx', 'Customer Workshop')
    expect(mocks.documents[0]).toMatchObject({
      creator: 'ID-8', title: 'ID-8 - Customer Workshop', description: 'Generated by ID-8 - Microsoft Innovation Hub',
    })
  })

  it('brands shared Teams/Outlook content and browser metadata consistently', () => {
    expect(buildTeamsSummary({ customerName: 'Contoso' })).toMatch(/^\*\*ID-8 Discovery/)
    const html = readFileSync(resolve(root, 'index.html'), 'utf8')
    expect(html).toContain('<meta name="application-name" content="ID-8"')
    expect(html).toContain('<meta property="og:site_name" content="ID-8"')
  })

  it('has no former product branding in active UI and export sources', () => {
    const files: string[] = []
    const visit = (directory: string) => {
      for (const entry of readdirSync(directory, { withFileTypes: true })) {
        const filename = resolve(directory, entry.name)
        if (entry.isDirectory()) visit(filename)
        else if (/\.(ts|tsx)$/.test(entry.name) && !/\.(test|spec)\./.test(entry.name)) files.push(filename)
      }
    }
    visit(resolve(root, 'src', 'components'))
    visit(resolve(root, 'src', 'lib'))
    for (const filename of files) {
      const source = readFileSync(filename, 'utf8')
        .replace(/^const LEGACY_MARKER_KEY = .*$/m, '')
      expect(source, filename).not.toMatch(/karabo/i)
    }
  })
})
